COMMANDS = (
    "- reproduce CI: `python -m unittest discover -s tests -v`\n"
    "- tests: `python -m unittest discover -s tests -v`\n"
    "- build: `python tools/gen_schema.py > build/schema.json`\n"
    "- generated check: compare `api/schema.json` with `build/schema.json`")

README = ("# todo\n\nTiny task model. `api/schema.json` is generated by "
          "`tools/gen_schema.py`.\n")


def build_with(dir, schema_bytes):
    build_repo(
        dir,
        {"README.md": README,
         "todo/__init__.py": "",
         "todo/model.py": MODEL,
         "tools/gen_schema.py": GEN,
         "api/schema.json": schema_bytes,
         "tests/__init__.py": "",
         "tests/test_model.py": TEST,
         ".pr-ready/profile.md": profile(COMMANDS, ["api/schema.json"])},
        {"todo/model.py": MODEL_NEW},
        "Add complete()", "feat/complete")


def build(dir):
    build_with(dir, SCHEMA_LF.replace("\n", "\r\n").encode("utf-8"))
